#!/usr/bin/env python3
"""Rasterises the transport icons into 8-bit alpha bitmaps (components/ui/icons.c).
The shapes are our own: plain triangles and rounded bars."""
import os

SS = 4  # supersampling factor


def tri(ax, ay, bx, by, cx, cy):
    def inside(x, y):
        d1 = (x - bx) * (ay - by) - (ax - bx) * (y - by)
        d2 = (x - cx) * (by - cy) - (bx - cx) * (y - cy)
        d3 = (x - ax) * (cy - ay) - (cx - ax) * (y - ay)
        neg = d1 < 0 or d2 < 0 or d3 < 0
        pos = d1 > 0 or d2 > 0 or d3 > 0
        return not (neg and pos)
    return inside


def rrect(x0, y0, x1, y1, r):
    def inside(x, y):
        if not (x0 <= x <= x1 and y0 <= y <= y1):
            return False
        cx = min(max(x, x0 + r), x1 - r)
        cy = min(max(y, y0 + r), y1 - r)
        return (x - cx) ** 2 + (y - cy) ** 2 <= r * r
    return inside


def render(w, h, shapes):
    out = []
    for py in range(h):
        for px in range(w):
            hits = 0
            for sy in range(SS):
                for sx in range(SS):
                    x = px + (sx + 0.5) / SS
                    y = py + (sy + 0.5) / SS
                    if any(s(x, y) for s in shapes):
                        hits += 1
            out.append(round(255 * hits / (SS * SS)))
    return out


ICONS = {
    "play": (64, 64, [tri(14, 6, 14, 58, 58, 32)]),
    "pause": (64, 64, [rrect(12, 6, 27, 58, 4), rrect(37, 6, 52, 58, 4)]),
    "next": (80, 48, [tri(4, 4, 4, 44, 40, 24), tri(40, 4, 40, 44, 76, 24)]),
    "prev": (80, 48, [tri(76, 4, 76, 44, 40, 24), tri(40, 4, 40, 44, 4, 24)]),
}

lines = ['/* Generated by tools/gen_icons.py - do not edit. */', '#include "lvgl.h"', '']
for name, (w, h, shapes) in ICONS.items():
    data = render(w, h, shapes)
    lines.append(f"static const uint8_t {name}_map[] = {{")
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(v) for v in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"const lv_image_dsc_t icon_{name} = {{")
    lines.append(f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {w}, .h = {h}, .stride = {w}}},")
    lines.append(f"    .data_size = sizeof({name}_map), .data = {name}_map,")
    lines.append("};")
    lines.append("")

path = os.path.join(os.path.dirname(__file__), "..", "components", "ui", "icons.c")
with open(path, "w") as f:
    f.write("\n".join(lines))
print("wrote", os.path.normpath(path))
